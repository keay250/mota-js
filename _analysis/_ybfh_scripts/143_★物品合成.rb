class Scene_Craft

  #--------------------------------------------------------------------------
  def initialize(list=[],craft_index=0)
    @list=list
    @craft_index=craft_index
  end
  
  #--------------------------------------------------------------------------
  def main
    @craft_window = Window_Craft.new(@list)
    @craft_window.index=@craft_index
    @confirm_window = Window_Base.new(120, 188, 400, 64)
    @confirm_window.contents = Bitmap.new(368, 32)
  #  @confirm_window.contents.font.name = "黑体"
    @confirm_window.contents.font.size = 20
    @actor_index=0
    @actor = $game_party.actors[@actor_index]
    @result_window = Window_EquipLeft.new(@actor,@actor_index)
    @item_window = Window_EquipHelp.new
    @ingredients_window=Window_CraftIngredients.new
    @yes_no_window = Window_Command.new(100, ["确定", "放弃"])
    @confirm_window.visible = false
    @confirm_window.z = 1500
    @yes_no_window.visible = false
    @yes_no_window.active = false
    @yes_no_window.index = 1
    @yes_no_window.x = 270
    @yes_no_window.y = 252
    @yes_no_window.z = 1500
    Graphics.transition
    loop do
      Graphics.update
      Input.update
      update
      if $scene != self
        break
      end
    end
    Graphics.freeze
    @craft_window.dispose
    @result_window.dispose
    @ingredients_window.dispose
    @confirm_window.dispose
    @yes_no_window.dispose
    @item_window.dispose
  end

  #--------------------------------------------------------------------------
  def update
    @craft_window.update
    @ingredients_window.update
    if @list.size > 0
    #  @result_window.set_result(@craft_window.recipe.result, @craft_window.recipe.result_type)
      @ingredients_window.set_ingredients(@craft_window.recipe.ingredients,
                                                           @craft_window.recipe.ingredient_types,
                                                           @craft_window.recipe.quantities)
    end
             
    if @save_index !=@craft_window.index
      @save_index=@craft_window.index
      @item_window.set_text(@craft_window.item == nil ? "" : @craft_window.item.id)
    end
    if @list.size > 0
      # 获取现在选中的物品
      item2 = @craft_window.item
      if item2 !=nil
        # 变更装备
        item1 = $data_weapons[@actor.equip_id[0]]
        last_hp = @actor.hp
        last_sp = @actor.sp
        $game_party.gain_weapon(item2.id, 1)
        @actor.equip(0, item2 == nil ? 0 : item2.id)
        # 获取变更装备后的能力值
        new_atk = @actor.str
        new_pdef = @actor.dex
        new_mdef = @actor.int
        new_maxhp = @actor.maxhp
        new_maxsp = @actor.maxsp
        new_power1 = @actor.power1
        new_power2 = @actor.power2
        new_power3 = @actor.power3
        new_hpre = @actor.hprecover
        new_mp = @actor.sprecover
        new_atkspe = @actor.atkspeed
        new_shield = @actor.shield
        new_magicdef = @actor.magicdef
        new_miss = @actor.miss
        # 返回到装备
        @actor.equip(0, item1 == nil ? 0 : item1.id)
        $game_party.gain_weapon(item2.id, -1)
        @actor.hp = last_hp
        @actor.sp = last_sp
        # 描画左窗口
        @result_window.set_new_parameters(new_atk, new_pdef, new_mdef,new_maxhp,new_maxsp, \
        new_power1,new_power2,new_power3,new_hpre,new_mp,new_atkspe,new_shield,new_magicdef,new_miss)
      end
    end

    if @craft_window.active
      update_craft
      return
    end
    if @yes_no_window.active
      confirm_update
      return
    end
  end

  #--------------------------------------------------------------------------
  def update_craft
    if Input.trigger?(Input::B)
      $game_system.se_play($data_system.cancel_se)
      $scene = Scene_Map.new
      return
    end
    if Input.trigger?(Input::C) and @list.size != 0
      @recipe = @craft_window.recipe
      if @recipe.have
        @yes_no_window.active = true
        @craft_window.active = false
      else
        $game_system.se_play($data_system.buzzer_se)
        return
      end
    end
  end

  #--------------------------------------------------------------------------
  def confirm_update
    @craft_index = @craft_window.index
    @confirm_window.visible = true
    @confirm_window.z = 1500
    @yes_no_window.visible = true
    @yes_no_window.active = true
    @yes_no_window.z = 1500
    @yes_no_window.update
    string = "确定要合成 " + @recipe.name.split(":")[0] + " 吗？"
    cw = @confirm_window.contents.text_size(string).width
    center = @confirm_window.contents.width/2 - cw /2
    unless @drawn
      @confirm_window.contents.draw_text(center, 0, cw, 30, string)
      @drawn = true
    end
    if Input.trigger?(Input::C)
      if @yes_no_window.index == 0
        $game_system.se_play($data_system.decision_se)
        @recipe.make
        $game_system.se_play($data_system.save_se)
        $scene=Scene_Craft.new(@list,@craft_index)
      else
        $game_system.se_play($data_system.cancel_se)
        $scene=Scene_Craft.new(@list,@craft_index)
      end
    end
    if Input.trigger?(Input::B)
      $game_system.se_play($data_system.cancel_se)
      $scene=Scene_Craft.new(@list,@craft_index)
    end
  end

end # of Scene_Craft

