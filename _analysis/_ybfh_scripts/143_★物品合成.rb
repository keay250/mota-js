      end
    end
  end

  #--------------------------------------------------------------------------
  def draw_item(index)
    recipe = @data[index]
    self.contents.font.color = recipe.have ? normal_color : disabled_color
    x = 16
    y = index * 32
    bitmap = RPG::Cache.icon(recipe.get_item.icon_name)
    @spr.bitmap.blt(x*2,y*2+32,bitmap, Rect.new(0, 0, 86, 64))
    self.contents.draw_text(x+36 , y, self.width-32, 32, recipe.name.split(":")[0], 0)
