class Game_Recipe

  attr_reader :ingredients
  attr_reader :quantities
  attr_reader :result
  attr_reader :result_type
  attr_reader :ingredient_types
  
 #----------------------------------------------------------------------
  def initialize( ingredients, ingredient_types, quantities, result, result_type)
    @ingredients = ingredients
    @ingredient_types = ingredient_types
    @quantities = quantities
    @result = result
    @result_type = result_type
  end
  
 #----------------------------------------------------------------------
  def name
    case @result_type
      when 0
        name = $data_items[@result].name
      when 1
        name = $data_armors[@result].name
      when 2
        name = $data_weapons[@result].name
    end
    return name
  end
  def get_item
    if @result_type==2
      return $data_weapons[@result]
    end
    return nil
  end
 
 #----------------------------------------------------------------------
  def have
    have_all = true
    for i in 0...@ingredients.size
      case @ingredient_types[i]
        when 0
          if $game_party.item_number(@ingredients[i]) < @quantities[i]
            have_all=false
          end
        when 1
          if $game_party.armor_number(@ingredients[i]) < @quantities[i]
            have_all=false
          end
        when 2
          a= $game_party.weapon_number(@ingredients[i])
          a = [a-1,0].max if $game_variables[181][@ingredients[i]]!=nil && $game_variables[181][@ingredients[i]]>0\
          && !$game_actors[$game_variables[1]+1].equip_id.include?(@ingredients[i]) && @ingredients[i]!=74
          if a < @quantities[i]
            have_all=false
          end
      end
    end
    return have_all
  end

 #----------------------------------------------------------------------
  def decrement
    for i in 0...@ingredients.size
      case @ingredient_types[i]
      when 0
        $game_party.lose_item(@ingredients[i], @quantities[i])
      when 1
        $game_party.lose_armor(@ingredients[i], @quantities[i])
      when 2
        $game_party.lose_weapon(@ingredients[i], @quantities[i])
      end
    end
  end

 #----------------------------------------------------------------------
  def make
    if have
      case @result_type
      when 0
        $game_party.gain_item(@result, 1)
      when 1
        $game_party.gain_armor(@result, 1)
      when 2
        $game_party.gain_weapon(@result, 1)
        a=$data_weapons[@result]
        if a.description[0,6]=="充能" && a.description.size>6
          $game_variables[181][a.id]=a.description[6,a.description.size-6].to_i
        end
        
        def equipup(a,b)
          if $game_variables[174]!=0
            if $game_variables[174][$game_variables[1]]!=nil
              for i in 0...10
                if $game_variables[174][$game_variables[1]][i]!=nil
                  for j in 0...6
                    if $game_variables[174][$game_variables[1]][i][j]==b
                      $game_variables[174][$game_variables[1]][i][j]=a
                    end
                  end
                end
              end
            end
          end
        end
        
        case a.id
        when 50
          equipup(a.id,29)
          for i in $game_variables[182]
            for j in 0...i.size
              i[j]=56 if i[j]==39
            end
          end
        when 51
          equipup(a.id,25)
        when 66
          equipup(a.id,61)
        when 76
          equipup(a.id,53)
          for i in $game_variables[182]
            for j in 0...i.size
              i[j]=121 if i[j]==57
            end
          end
        when 82
          equipup(a.id,50)
        when 86
          equipup(a.id,42)
        when 89
          equipup(a.id,64)
        when 79
          get_achievement(17) #传奇装备
        when 126
          equipup(a.id,66)
          $game_variables[231]=126
        when 122
          equipup(a.id,121)
        when 131
          equipup(a.id,123)
          for i in $game_variables[182]
            for j in 0...i.size
              i[j]=170 if i[j]==163
            end
          end
        end
      end
      decrement
    end
  end
  
 #----------------------------------------------------------------------
  def == (recipe)
    if recipe.is_a?(Game_Recipe)
      equal = true
      if recipe.ingredients != self.ingredients
        equal = false
      end
      if recipe.ingredient_types != self.ingredient_types
        equal = false
      end
      if recipe.quantities != self.quantities
        equal = false
      end
      if recipe.result != self.result
        equal=false
      end
      if recipe.result_type != self.result_type
        equal = false
      end
    else
      equal = false
    end
    return equal
  end
  
end # of Game_Recipe class

