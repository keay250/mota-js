class Window_NameInputA < Window_Base    
  #--------------------------------------------------------------------------
  # ● 初始化对像
  #--------------------------------------------------------------------------
  def initialize
    super(0, 128, 640, 352)
    self.contents = Bitmap.new(width - 32, height - 32)
    update_character_table(false)
    refresh
    update_cursor_rect
  end
  #--------------------------------------------------------------------------
  # ● 获取文字
  #--------------------------------------------------------------------------
  def character
    return @character_table[@index]
  end
  #--------------------------------------------------------------------------
  # ● 刷新
  #--------------------------------------------------------------------------
  def refresh
    @index = 0
    self.contents.clear
    for i in 0..199
      x = 4 + i % 20 * 30
      y = i / 20 * 29 
      self.contents.draw_text(x, y, 30, 29, @character_table[i], 1)
    end
    self.contents.draw_text(544,291, 60, 29, "确定", 1)
  end
  #--------------------------------------------------------------------------
  # ● 刷新光标矩形
  #--------------------------------------------------------------------------
  def update_cursor_rect
    # 光标位置在 [确定] 的情况下
    if @index >= 200
      self.cursor_rect.set(544,291, 60,29)
    # 光标位置在 [确定] 以外的情况下
    else
      x = 4 + @index % 20 * 30
      y = @index / 20 * 29
      self.cursor_rect.set(x, y, 30, 29)
    end
  end
  #--------------------------------------------------------------------------
  # ● 刷新画面
  #--------------------------------------------------------------------------
  def update
    super
    # 光标位置在 [确定] 的情况下
    if @index >= 200
      # 光标下
      if Input.trigger?(Input::DOWN)
        $game_system.se_play($data_system.cursor_se)
        @index -= 200
      end
      # 光标上
      if Input.trigger?(Input::UP)
        $game_system.se_play($data_system.cursor_se)
        @index -= 20
      end
    # 光标位置在 [确定] 以外的情况下
    else
      # 按下方向键右的情况下
      if Input.repeat?(Input::RIGHT)
        # 光标向右移动
        $game_system.se_play($data_system.cursor_se)
        if @index % 20 < 19
          @index += 1
        else
          @index -= 19
        end
      end
      # 按下方向键左的情况下
      if Input.repeat?(Input::LEFT)
        # 光标向左移动
        $game_system.se_play($data_system.cursor_se)
        if @index % 20 > 0
          @index -= 1
        else
          @index += 19
        end
      end
      # 按下方向键下的情况下
      if Input.repeat?(Input::DOWN)
        # 光标向下移动
        $game_system.se_play($data_system.cursor_se)
        if @index < 200
          @index += 20
        end
      end
      # 按下方向键上的情况下
      if Input.repeat?(Input::UP)
          $game_system.se_play($data_system.cursor_se)
          if @index > 19
            @index -= 20
          else
            @index += 200
          end
      end
      # L 键与 R 键被按下的情况下
      if Input.repeat?(Input::L) or Input.repeat?(Input::R)
        # 左右十格跳动
        $game_system.se_play($data_system.cursor_se)
        if @index % 20 < 10
          @index += 10
        else
          @index -= 10
        end
      end
    end
    update_cursor_rect
  end
